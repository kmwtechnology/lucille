  /**
   * Holds various resources instantiated during a run so that the shutdown hook installed by main() can attempt to
   * cleanly close or stop them when the process is told to shut down (SIGINT or SIGTERM)
   */
  static class RunnerState {
    private Publisher publisher;
    private Connector connector;
    private WorkerPool workerPool;
    private Indexer indexer;
    private Thread indexerThread;

    public RunnerState() {
    }

    public void set(Publisher publisher, Connector connector, WorkerPool workerPool, Indexer indexer, Thread thread) {
      this.publisher = publisher;
      this.connector = connector;
      this.workerPool = workerPool;
      this.indexer = indexer;
      this.indexerThread = thread;
    }

    public void clear() {
      publisher = null;
      connector = null;
      workerPool = null;
      indexer = null;
      indexerThread = null;
    }

    public void close() {
      if (connector != null) {
        try {
          log.info("Closing current Connector...");
          connector.close();
        } catch (Exception e) {
          log.error("Error closing Connector", e);
        }
      }
      if (publisher != null) {
        try {
          log.info("Closing current Publisher...");
          publisher.close();
        } catch (Exception e) {
          log.error("Error closing Publisher", e);
        }
      }
      if (workerPool != null) {
        try {
          log.info("Stopping current Worker pool...");
          workerPool.stop();
          workerPool.join(DEFAULT_WORKER_INDEXER_JOIN_TIMEOUT);
        } catch (Exception e) {
          log.error("Error stopping WorkerPool", e);
        }
      }
      if (indexer != null) {
        try {
          log.info("Stopping current Indexer...");
          indexer.terminate();
          if (indexerThread != null) {
            indexerThread.join(DEFAULT_WORKER_INDEXER_JOIN_TIMEOUT);
          }
        } catch (Exception e) {
          log.error("Error stopping Indexer", e);
        }
      }
    }
  }

  /**
   * Runs the configured connectors. NOTE: option names are case insensitive.
   * <p>
   * no args: pipelines workers and indexers will be executed in separate threads within the same JVM; communication
   * between components will take place in memory and Kafka will not be used
   * <p>
   * -distributed: connectors will be run, sending documents and receiving events via Kafka. Pipeline workers
   * and indexers will not be run. The assumption is that these have been deployed as separate processes.
   * <p>
   * -external: modified local mode where workers and indexers are started as separate threads within the same JVM and kafka is
   * used for communication between them.
   * <p>
   * -render: prints out the effective/actual config in the exact form it will be seen by Lucille during the run
   * <p>
   * The process exits 0 when the run succeeds and 1 when it fails. On SIGINT or SIGTERM the shutdown hook stops and
   * closes the run's components, and the process exits with the JVM's signal status. The body of this entry point is
   * {@link Launch#runner}, which the other component entry points share their process-level behaviour with.
   */
  public static void main(String[] args) throws Exception {
    Launch.runner(args);
  }

